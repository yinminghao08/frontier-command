export function createWorld(seed = 236807): WorldState {
  const ships: Ship[] = specs.map((s, i) => ({
    ...s,
    x: BASE.x + (i - 1) * 17,
    y: BASE.y + 24,
    operatorId: `ops-${s.id}`,
    hull: 100,
    shield: s.maxShield,
    heading: -Math.PI / 2,
    throttle: 0,
    status: 'docked',
    order: 'hold',
    missionId: null,
    targetId: null,
    path: [],
    trail: [],
    cooldown: 0,
    cargo: 0,
    repair: 0,
    tow: 0,
    emergency: false,
    helm: { turn: 0, throttle: 0 },
  }));
  const missions: Mission[] = tasks.map(
    ([
      id,
      name,
      kind,
      locationId,
      brief,
      requirement,
      attention,
      risk,
      duration,
      cargoRequired,
      reward,
    ]) => ({
      id,
      name,
      kind,
      locationId,
      brief,
      requirement,
      attention,
      risk,
      duration,
      cargoRequired,
      reward,
      phase: 'available',
      shipId: null,
      route: 'safe',
      started: 0,
      work: 0,
      decisionAt: 0,
      choice: null,
      deadline: kind === 'supply' ? (cargoRequired > 20 ? 300 : 240) : 0,
      settled: false,
      run: 0,
      result: '',
      contactId: null,
      damage: 0,
    }),
  );
  return {
    version: 1,
    tick: 0,
    time: 0,
    seed: seed >>> 0,
    initialSeed: seed >>> 0,
    paused: true,
    speed: 1,
    manualShipId: null,
    commander: { id: 'commander', name: '舰队指挥官', rank: 'COMMODORE' },
    operators: ships.map((s) => ({
      id: s.operatorId,
      shipId: s.id,
      kind: 'rules',
      name: `${s.name} 规则驾驶系统`,
    })),
    ships,
    missions,
    locations: structuredClone(LOCATIONS),
    contacts: [],
    resources: { materials: 100, supplies: 140, science: 0, allocation: 120, intel: 0 },
    threat: 32,
    logs: [
      {
        id: 1,
        time: 0,
        level: 'info',
        text: '曙光基地指挥权已移交。三舰就绪，六项行动待命。世界已暂停，请派遣舰船后启动。',
      },
    ],
    nextLog: 2,
    nextContact: 1,
    nextIncursion: 210,
    beams: [],
  };
}
